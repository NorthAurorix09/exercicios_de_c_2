
/* Um tipo de dado se trata da forma como
você guarda a informação de uma variável.

    Eles servem pra definir o quanto de memória
vai ser alocada pra tal variável (algumas
variáveis, como char, só tem um caractere definido
diferentemente de arrays, por exemplo, que possuem
vários elementos e, portanto, necessitam de mais
memória) para usar o mínimo de memória possível.

    Também servem pra definir quais métodos
são compatíveis com tal tipo de dado e como
vão se comportar diante certas operações (por
exemplo,"+" representa adição para inteiros, mas
concatenação para strings/char )*/