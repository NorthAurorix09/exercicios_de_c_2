
/* Tipagem estática é quando o tipo de dado
da variável é declarado e não pode ser mudado
durante o programa. Já na tipagem dinâmica
o tipo de dado pode mudar conforme o tempo,
e os erros entre compatibilidade de tipo de 
dado e métodos, operações só aparecer durante
a execução do programa.

Exemplos de tipagem estática: C, C++, Java
Exemplos de tipagem dinâmica: Python, JavaScript, PHP

Uma linguagem de tipagem estática geralmente é mais 
rápida que uma de tipagem dinâmica pois, na estática
o tipo de dado da variável já é verificado com 
antecedência e verifica com antecedência se as operações
e métodos são válidos, como, por exemplo, em C
verifica-se todos os erros na compilação e com antecedência
já encontramos operações inválidas. Já na linguagem dinâmica
a linguagem necessita estar preparada a cada linha
e verificar toda hora numa operação envolvendo tais variáveis
se esta é válida (requer mais processamento), como por exemplo
em Python, linguagem que lê linha por linha e pode apenas encontrar
um erro depois, e ter que verificar várias vezes se a operação
é válida.*/